<h2 class="wp-block-heading has-dpsg-blau-color has-text-color">Häufige Fragen (FAQ)</h2>
<!-- /wp:heading -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Dürfen Mädchen mitmachen?</summary>
<!-- wp:paragraph -->
<p>Ja, selbstverständlich! Die DPSG ist ein koedukativer Verband. In fast allen Stämmen leiten und erleben Mädchen und Jungen das Pfadfinden gemeinsam.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Ab welchem Alter kann mein Kind Pfadfinder werden?</summary>
<!-- wp:paragraph -->
<p>Bereits ab dem Kindergarten-Alter kann man in manchen Stämmen in der Bibergruppe mitmachen. Regulär beginnt die Wölflingsstufe im Alter von 6-7 Jahren.</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Was kostet die Mitgliedschaft?</summary>
<!-- wp:paragraph -->
<p>Der Jahresbeitrag der DPSG liegt bei einem bundesweiten Sockelbetrag (jährlich über dpsg.de kommuniziert). Dazu kommt oft ein kleiner Stammesbeitrag für Zelte und Material. Familien und sozial Schwächere können eine Ermäßigung beantragen (Sozialermäßigung).</p>
<!-- /wp:paragraph -->
</details>
<!-- /wp:details -->

<!-- wp:details -->
<details class="wp-block-details"><summary>Wie ist es mit der Religion?</summary>
<!-- wp:paragraph -->
<p>Die DPSG ist ein katholischer Verband, wir sind aber offen für Mitglieder aller Konfessionen und Religionen. Jeder bringt sich entsprechend seiner Fähigkeiten ein.</p>
<!-- /wp:paragraph -->
</details>
